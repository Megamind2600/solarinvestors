"""Fetch a big pool of *real*, open-licensed meditative instrumental music.

Everything here is downloaded from sources that publish explicit free licenses,
and only tracks whose license is genuinely usable in public (and possibly
monetised) Reels are kept:

    kept      CC0 / Public Domain Mark / PD-old / CC-BY / CC-BY-SA / GFDL
    rejected  anything with -NC (non-commercial) or -ND (no derivatives)

Vocals/chanting are filtered out by keyword, as are clips too short to cut a
45 s window from.  Each kept file is decoded once and re-written as a clean
44.1 kHz stereo WAV under music/library/audio/, and music/library/manifest.json
records the license/attribution of every track so the repo stays auditable.

    python scripts/fetch_music.py --target 240 --dry-run   # see the plan
    python scripts/fetch_music.py --target 240               # actually fetch
    python scripts/fetch_music.py --provider freesound --token-from-env
    python scripts/fetch_music.py --list                     # what we have now

Sources (all verified reachable on 2026-09-10):
  * Freesound  - thousands of CC0 field/studio recordings (tanpura, bansuri,
                 singing bowls, rain).  Originals need a free API token; with
                 none we fall back to the public preview mp3s.
  * archive.org- netlabel releases published whole under CC0/CC-BY, plus a
                 licenseurl search field so filtering is exact, not guessed.
  * Wikimedia Commons - encyclopedic public-domain/CC audio (solo cello, harp,
                 sitar ragas); license comes from each file's extmetadata.
  * music/incoming - your own files; put a LICENSE.txt beside them.

Requires network access (this sandbox has none, CI/GitHub Actions does).
"""
